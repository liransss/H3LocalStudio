const { chromium } = require('./browser-tools/node_modules/playwright-core');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1600, height: 1050 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('http://127.0.0.1:1420');
  assert.equal((await (await page.request.get('http://127.0.0.1:7331/api/health')).json()).mock_mode, true);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByLabel('Prompt', {exact: true}).fill('A temporary draft');
  await page.getByRole('button', {name: 'New creation', exact: true}).click();
  assert.equal(await page.getByLabel('Prompt', {exact: true}).inputValue(), '');
  await page.getByRole('button', {name: 'Dismiss mock information'}).click();
  await page.getByRole('button', {name: 'Add image', exact: true}).waitFor();
  const uploadResponse = page.waitForResponse(r => r.url().includes('reference-assets') && r.request().method() === 'POST');
  const transfer = await page.evaluateHandle(bytes => {
    const data = new DataTransfer();
    data.items.add(new File([new Uint8Array(bytes)], 'studio-ui-validation.png', {type: 'image/png'}));
    return data;
  }, [...fs.readFileSync('.artifacts/ui-review/reference.png')]);
  await page.locator('.reference-dropzone').dispatchEvent('drop', {dataTransfer: transfer});
  assert.equal((await uploadResponse).status(), 201);
  const reference = page.locator('.reference-card').filter({hasText:'studio-ui-validation.png'});
  await reference.waitFor();
  await reference.getByRole('combobox').selectOption('first_frame');
  await reference.getByRole('textbox').fill('Preserve the frame composition');
  await page.getByRole('combobox', {name: 'Generation mode', exact:true}).selectOption('i2v');
  assert.match(await page.locator('.settings-card').innerText(), /I2V/);
  await page.screenshot({path:'.artifacts/ui-review/after-references.png'});
  await reference.getByRole('button', {name:'Remove studio-ui-validation.png'}).click();
  assert.equal(await reference.count(),0);
  await page.getByRole('combobox', {name:'Generation mode',exact:true}).selectOption('auto');
  const generations = await (await page.request.get('http://127.0.0.1:7331/api/generations')).json();
  const generation = generations.find(g => g.id === 'f0452590-f987-4b64-a553-894e414dbfe6');
  assert(generation);
  await page.getByRole('button', {name:'History',exact:true}).click();
  await page.getByPlaceholder('Search prompts…').fill(generation.prompt);
  await page.getByRole('button', {name:`Open ${generation.prompt}`,exact:true}).click();
  await page.getByRole('button', {name:'Compare original / upscaled',exact:true}).click();
  await page.waitForFunction(() => [...document.querySelectorAll('.video-comparison video')].length===2 && [...document.querySelectorAll('.video-comparison video')].every(v=>v.readyState>=2));
  await page.getByRole('slider', {name:'Original and upscaled comparison split'}).fill('30');
  assert.equal(await page.getByRole('slider').getAttribute('aria-valuetext'),'30% original, 70% upscaled');
  await page.locator('.video-comparison video').first().evaluate(v=>v.play());
  await page.waitForTimeout(800);
  const sync = await page.locator('.video-comparison').evaluate(el => [...el.querySelectorAll('video')].map(v=>({time:v.currentTime,paused:v.paused})));
  assert(sync.every(v=>!v.paused));
  assert(Math.abs(sync[0].time-sync[1].time)<.3);
  await page.locator('.video-comparison video').first().evaluate(v=>{ v.pause(); v.currentTime=1; });
  await page.waitForTimeout(200);
  await page.screenshot({path:'.artifacts/ui-review/after-comparison.png'});
  await page.getByRole('button', {name:'Close result'}).focus();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Delete');
  await page.keyboard.press('Escape');
  await page.getByRole('button', {name:'Create',exact:true}).click();
  const robot = page.locator('.recent-filmstrip button').filter({hasText:'cute white service robot'});
  if (await robot.count()) await robot.first().click();
  await page.screenshot({path:'.artifacts/ui-review/after-create-final.png'});
  for(const width of [1280,768,390,320]) {
    await page.setViewportSize({width,height:900});
    await page.screenshot({path:`.artifacts/ui-review/after-create-final-${width}.png`});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    const bounds = await page.getByRole('button',{name:'Generate mock video',exact:true}).boundingBox();
    assert(bounds.y+bounds.height<=900);
  }
  fs.writeFileSync('.artifacts/ui-review/interaction-results.json',JSON.stringify({referenceDrop:true,referenceRoles:true,referenceRemoval:true,newCreationClearsDraft:true,comparison:'existing original and SeedVR2 files; no inference',synchronizedPlayback:sync,focusTrap:true,consoleErrors:errors},null,2));
  await browser.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: reference drag/drop, roles, removal, new draft, existing-video comparison, playback synchronization, focus trap, sticky generation action, zero console errors.');
})().catch(e=>{console.error(e);process.exit(1)});
